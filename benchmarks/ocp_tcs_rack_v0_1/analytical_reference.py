"""Steady energy-balance reference for the synthetic OCP-aligned rack case.

This is a verification oracle, not a calibrated rack or CDU model. The liquid
path is represented by a single technology-cooling-system (TCS) control volume.
"""

import json
from pathlib import Path


DEFAULT_CASE_PATH = Path(__file__).with_name("case.json")


def evaluate_case_file(case_path: str | Path = DEFAULT_CASE_PATH) -> dict[str, float]:
    """Evaluate one canonical case JSON file without external dependencies.

    The file must preserve the explicitly declared partition between liquid and
    residual-air heat. This guard prevents a configuration from claiming a
    closed rack energy balance when its two heat-path fractions are inconsistent.
    """
    with Path(case_path).open(encoding="utf-8") as case_file:
        case = json.load(case_file)

    liquid_capture_fraction = case["rack"]["liquid_capture_fraction"]
    residual_air_heat_fraction = case["rack"]["residual_air_heat_fraction"]
    if abs(liquid_capture_fraction + residual_air_heat_fraction - 1.0) > 1e-12:
        raise ValueError(
            "liquid_capture_fraction and residual_air_heat_fraction must sum to 1"
        )

    return evaluate_steady_case(
        it_heat_w=case["rack"]["it_heat_w"],
        liquid_capture_fraction=liquid_capture_fraction,
        tcs_supply_temperature_c=case["tcs"]["supply_temperature_c"],
        tcs_mass_flow_kg_s=case["tcs"]["mass_flow_kg_s"],
        coolant_specific_heat_j_kg_k=case["fluid"]["specific_heat_j_kg_k"],
    )


def evaluate_steady_case(
    *,
    it_heat_w: float,
    liquid_capture_fraction: float,
    tcs_supply_temperature_c: float,
    tcs_mass_flow_kg_s: float,
    coolant_specific_heat_j_kg_k: float,
) -> dict[str, float]:
    """Return steady heat-path and TCS-temperature quantities in SI units.

    The sign convention is positive heat generated by the IT load and positive
    heat removed through the liquid or residual air paths. With no modeled
    energy storage, the rack residual is ``Q_IT - Q_liquid - Q_air``.
    """
    if it_heat_w < 0.0:
        raise ValueError("it_heat_w must be nonnegative")
    if not 0.0 <= liquid_capture_fraction <= 1.0:
        raise ValueError("liquid_capture_fraction must be between 0 and 1")
    if tcs_mass_flow_kg_s <= 0.0:
        raise ValueError("tcs_mass_flow_kg_s must be positive")
    if coolant_specific_heat_j_kg_k <= 0.0:
        raise ValueError("coolant_specific_heat_j_kg_k must be positive")

    liquid_heat_w = it_heat_w * liquid_capture_fraction
    air_heat_w = it_heat_w - liquid_heat_w
    tcs_temperature_rise_k = liquid_heat_w / (
        tcs_mass_flow_kg_s * coolant_specific_heat_j_kg_k
    )
    tcs_return_temperature_c = tcs_supply_temperature_c + tcs_temperature_rise_k
    rack_energy_residual_w = it_heat_w - liquid_heat_w - air_heat_w

    return {
        "it_heat_w": it_heat_w,
        "liquid_heat_w": liquid_heat_w,
        "air_heat_w": air_heat_w,
        "tcs_temperature_rise_k": tcs_temperature_rise_k,
        "tcs_supply_temperature_c": tcs_supply_temperature_c,
        "tcs_return_temperature_c": tcs_return_temperature_c,
        "rack_energy_residual_w": rack_energy_residual_w,
    }


if __name__ == "__main__":
    print(json.dumps(evaluate_case_file(), indent=2, sort_keys=True))
