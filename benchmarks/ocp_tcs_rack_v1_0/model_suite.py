"""Reference models for the synthetic liquid-cooled rack comparison suite.

The module keeps the model boundary intentionally narrow. Heat generated by IT
is partitioned into liquid and residual-air paths at the rack boundary. The
reduced-order model has one effective hardware node and one mixed-coolant node;
its parameters are illustrative synthetic quantities, not fitted equipment
properties.
"""

from __future__ import annotations

import json
from pathlib import Path


DEFAULT_SUITE_PATH = Path(__file__).with_name("suite.json")


def evaluate_quasi_steady_case(
    *,
    it_heat_w: float,
    liquid_capture_fraction: float,
    supply_temperature_c: float,
    mass_flow_kg_s: float,
    specific_heat_j_kg_k: float,
) -> dict[str, float]:
    """Evaluate the declared steady TCS rack control-volume balance.

    Positive heat is generated by IT and removed through the liquid or residual
    air path. The model includes no thermal storage, hydraulic loss, or CDU.
    """
    if it_heat_w < 0.0:
        raise ValueError("it_heat_w must be nonnegative")
    if not 0.0 <= liquid_capture_fraction <= 1.0:
        raise ValueError("liquid_capture_fraction must be between 0 and 1")
    if mass_flow_kg_s <= 0.0:
        raise ValueError("mass_flow_kg_s must be positive")
    if specific_heat_j_kg_k <= 0.0:
        raise ValueError("specific_heat_j_kg_k must be positive")

    liquid_heat_w = it_heat_w * liquid_capture_fraction
    residual_air_heat_w = it_heat_w - liquid_heat_w
    heat_capacity_rate_w_k = mass_flow_kg_s * specific_heat_j_kg_k
    temperature_rise_k = liquid_heat_w / heat_capacity_rate_w_k
    return_temperature_c = supply_temperature_c + temperature_rise_k
    energy_residual_w = it_heat_w - liquid_heat_w - residual_air_heat_w
    return {
        "it_heat_w": it_heat_w,
        "liquid_heat_w": liquid_heat_w,
        "residual_air_heat_w": residual_air_heat_w,
        "heat_capacity_rate_w_k": heat_capacity_rate_w_k,
        "temperature_rise_k": temperature_rise_k,
        "supply_temperature_c": supply_temperature_c,
        "return_temperature_c": return_temperature_c,
        "energy_residual_w": energy_residual_w,
    }


def simulate_two_node_case(
    *,
    supply_temperature_c: float,
    mass_flow_kg_s: float,
    specific_heat_j_kg_k: float,
    liquid_heat_w: float,
    heat_capacity_hardware_j_k: float,
    heat_capacity_coolant_j_k: float,
    ua_w_k: float,
    duration_s: float,
    time_step_s: float,
    initial_hardware_temperature_c: float | None = None,
    initial_return_temperature_c: float | None = None,
) -> list[dict[str, float]]:
    """Integrate a two-node hardware/coolant model with forward Euler steps.

    ``T_h`` represents an effective heat-producing hardware/cold-plate node and
    ``T_r`` represents a mixed TCS-return node. At every time step,

    ``C_h dT_h/dt = Q_liquid - UA (T_h - T_r)`` and
    ``C_f dT_r/dt = UA (T_h - T_r) - m_dot c_p (T_r - T_supply)``.

    The returned residual evaluates the same equations at the reported state;
    it is a conservation check of the numerical update, not an experimental
    uncertainty estimate.
    """
    positive_parameters = {
        "mass_flow_kg_s": mass_flow_kg_s,
        "specific_heat_j_kg_k": specific_heat_j_kg_k,
        "heat_capacity_hardware_j_k": heat_capacity_hardware_j_k,
        "heat_capacity_coolant_j_k": heat_capacity_coolant_j_k,
        "ua_w_k": ua_w_k,
        "duration_s": duration_s,
        "time_step_s": time_step_s,
    }
    for name, value in positive_parameters.items():
        if value <= 0.0:
            raise ValueError(f"{name} must be positive")
    if liquid_heat_w < 0.0:
        raise ValueError("liquid_heat_w must be nonnegative")

    step_count = round(duration_s / time_step_s)
    if abs(step_count * time_step_s - duration_s) > 1.0e-9:
        raise ValueError("duration_s must be an integer multiple of time_step_s")

    hardware_temperature_c = (
        supply_temperature_c if initial_hardware_temperature_c is None else initial_hardware_temperature_c
    )
    return_temperature_c = (
        supply_temperature_c if initial_return_temperature_c is None else initial_return_temperature_c
    )
    heat_capacity_rate_w_k = mass_flow_kg_s * specific_heat_j_kg_k
    rows: list[dict[str, float]] = []
    for index in range(step_count + 1):
        heat_transfer_w = ua_w_k * (hardware_temperature_c - return_temperature_c)
        liquid_rejection_w = heat_capacity_rate_w_k * (return_temperature_c - supply_temperature_c)
        hardware_rate_k_s = (liquid_heat_w - heat_transfer_w) / heat_capacity_hardware_j_k
        coolant_rate_k_s = (heat_transfer_w - liquid_rejection_w) / heat_capacity_coolant_j_k
        residual_w = (
            liquid_heat_w
            - liquid_rejection_w
            - heat_capacity_hardware_j_k * hardware_rate_k_s
            - heat_capacity_coolant_j_k * coolant_rate_k_s
        )
        rows.append(
            {
                "time_s": index * time_step_s,
                "supply_temperature_c": supply_temperature_c,
                "hardware_temperature_c": hardware_temperature_c,
                "return_temperature_c": return_temperature_c,
                "liquid_heat_w": liquid_heat_w,
                "heat_transfer_w": heat_transfer_w,
                "liquid_rejection_w": liquid_rejection_w,
                "energy_residual_w": residual_w,
            }
        )
        hardware_temperature_c += hardware_rate_k_s * time_step_s
        return_temperature_c += coolant_rate_k_s * time_step_s
    return rows


def load_suite(suite_path: str | Path = DEFAULT_SUITE_PATH) -> dict:
    """Load the public, synthetic suite metadata."""
    with Path(suite_path).open(encoding="utf-8") as source:
        suite = json.load(source)
    if suite.get("evidence_class") != "synthetic_derived":
        raise ValueError("suite must declare synthetic_derived evidence")
    if suite.get("validation_state") != "not_validated":
        raise ValueError("suite must declare not_validated state")
    return suite
